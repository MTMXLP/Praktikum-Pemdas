import math

laps = 5
total_distance = 14
radius = total_distance / (laps * 2 * math.pi)
print(f"Diketahui :")
print(f"Pak Dengklek mengelilingi taman = {laps} Putaran")
print(f"Jarak tempuh Pak Dengklek = {total_distance} Kilometer")
print(f"Jawaban :")
print(f"Jari-jari taman yang dikelilingi Pak Dengklek adalah {radius:.2f} Kilometer")
